const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://127.0.0.1:${PORT}`);
  try {
    if (req.method === 'GET' && url.pathname === '/') {
      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
      res.end(HTML);
      return;
    }
    if (req.method === 'GET' && url.pathname === '/api/links') {
      res.writeHead(200, { 'Content-Type': 'application/json; charset=utf-8' });
      res.end(JSON.stringify(snapshot()));
      return;
    }
    if (req.method === 'POST' && (url.pathname === '/api/update' || url.pathname === '/api/regen')) {
      let body = '';
      for await (const chunk of req) body += chunk;
      if (url.pathname === '/api/update') {
        const { index, file } = JSON.parse(body || '{}');
        const links = loadLinks();
        if (links.tokens[index]) links.tokens[index].file = file;
        saveLinks(links);
        const regen = regenerate(links);
        res.writeHead(200, { 'Content-Type': 'application/json; charset=utf-8' });
        res.end(JSON.stringify({ ...snapshot(), regen }));
      } else {
        const links = loadLinks();
        const regen = regenerate(links);
        res.writeHead(200, { 'Content-Type': 'application/json; charset=utf-8' });
        res.end(JSON.stringify({ ...snapshot(), regen }));
      }
      return;
    }
    res.writeHead(404); res.end('not found');
  } catch (e) {
    res.writeHead(500, { 'Content-Type': 'application/json; charset=utf-8' });
    res.end(JSON.stringify({ error: String(e?.message ?? e) }));
  }
});

server.on('error', (e) => {
  if (e.code === 'EADDRINUSE') {
    console.log(`secrets-link already running at http://127.0.0.1:${PORT} — opening it`);
    try { execSync(`start http://127.0.0.1:${PORT}`); } catch {}
    process.stdin.resume();
    return;
  }
  throw e;
});

server.listen(PORT, '127.0.0.1', () => {
  console.log(`secrets-link panel: http://127.0.0.1:${PORT}`);
  const { wrote, error } = regenerate(loadLinks());
  console.log(wrote ? `secrets.cmd regenerated: ${loadLinks().target}` : `secrets.cmd NOT written: ${error ?? 'no target'}`);
  try { execSync(`start http://127.0.0.1:${PORT}`); } catch {}
});
