// secrets-link-web.mjs — multi-workspace local panel for secrets.cmd ⇄ G:\KEY links.
// Tokens live in the FILE CONTENT under G:\KEY; secrets.cmd only references the path
// (batch `for /f` reads the content at runtime). Rotate = edit file content; re-link = change path.
// Multi-AGENT: links.json holds a `workspaces[]` array — each workspace has its own
// target secrets.cmd + tokens + extra, so DSH/Codex/Claude (or machine A/B/C) each get
// their own config. Select a workspace in the panel to manage that one.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync, execFileSync } from 'node:child_process';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const LINKS_PATH = path.join(DIR, 'links.json');
const PORT = Number(process.env.SECRETS_LINKS_PORT ?? 7782);

function loadLinks() {
  const raw = JSON.parse(fs.readFileSync(LINKS_PATH, 'utf8'));
  // migration: old flat {tokens, extra, target} -> {workspaces:[...], active:0}
  if (!raw.workspaces) {
    raw.workspaces = [{ name: '默认', target: raw.target || '', tokens: raw.tokens || [], extra: raw.extra || {} }];
    delete raw.target; delete raw.tokens; delete raw.extra;
    raw.active = 0;
  }
  if (raw.active == null || !raw.workspaces[raw.active]) raw.active = 0;
  if (!raw.workspaces.length) raw.workspaces.push({ name: '默认', target: '', tokens: [], extra: {} });
  return raw;
}
function saveLinks(links) {
  fs.writeFileSync(LINKS_PATH, JSON.stringify(links, null, 2) + '\n', 'utf8');
}
function activeWs(links) {
  return links.workspaces[links.active] || links.workspaces[0];
}
const PY = process.platform === 'win32' ? 'python' : 'python3';
const DECRYPT_RUNTIME = path.join(DIR, 'decrypt-runtime.py');

function isZip(file) {
  return /\.zip$/i.test(file || '');
}
function readTokenFile(file, identity, ageBin) {
  try {
    if (isZip(file) && identity) {
      return execFileSync(PY, [DECRYPT_RUNTIME, file, ageBin, identity], { encoding: 'utf8' }).trim();
    }
    return fs.readFileSync(file, 'utf8').trim();
  } catch { return null; }
}
function mask(token) {
  if (token == null) return { ok: false, text: '（文件缺失）' };
  if (token === '') return { ok: false, text: '（文件为空）' };
  return { ok: true, text: token.slice(0, 4) + '…' + token.slice(-2) + '（len ' + token.length + '）' };
}
function generateSecretsCmd(ws) {
  const lines = [
    '@echo off',
    'rem Generated by secrets-link panel (workspace: ' + (ws.name || '默认') + '). Tokens live in G:\\KEY file CONTENT.',
    ''
  ];
  for (const [k, v] of Object.entries(ws.extra ?? {})) lines.push('set "' + k + '=' + v + '"');
  lines.push('');
  for (const t of ws.tokens) {
    if (isZip(t.file) && ws.age && ws.age.identity) {
      const ab = (ws.age.bin) || 'age';
      lines.push(`for /f "delims=" %%i in ('${PY} ${DECRYPT_RUNTIME} ${t.file} ${ab} ${ws.age.identity}') do set "${t.var}=%%i"`);
    } else {
      lines.push('for /f "usebackq delims=" %%i in ("' + t.file + '") do set "' + t.var + '=%%i"');
    }
  }
  lines.push('');
  return lines.join('\r\n');
}
function regenerate(links) {
  const ws = activeWs(links);
  const unencrypted = ws.tokens.filter(t => !isZip(t.file)).map(t => t.var);
  if (unencrypted.length) {
    return { target: ws.target, wrote: false, error: '有未加密的 token（非 .zip），拒绝生成 secrets.cmd：' + unencrypted.join(', ') };
  }
  const cmd = generateSecretsCmd(ws);
  let target = ws.target, wrote = false, error = null;
  if (target) {
    try {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, cmd, 'utf8');
      wrote = true;
    } catch (e) { error = String(e?.message ?? e); }
  }
  return { target, wrote, error };
}
function snapshot() {
  const links = loadLinks();
  const ws = activeWs(links);
  const identity = (ws.age && ws.age.identity) || '';
  const ageBin = (ws.age && ws.age.bin) || 'age';
  const tokens = ws.tokens.map((t) => {
    const content = readTokenFile(t.file, identity, ageBin);
    const m = mask(content);
    return { var: t.var, file: t.file, exists: content != null, mask: m.text };
  });
  return {
    workspaces: links.workspaces.map((w, i) => ({ name: w.name, target: w.target, index: i })),
    active: links.active,
    target: ws.target,
    tokens,
  };
}

