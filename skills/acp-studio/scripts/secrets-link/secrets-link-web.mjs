// secrets-link-web.mjs — zero-dependency local panel for the secrets.cmd ⇄ G:\KEY link.
// Tokens live in the FILE CONTENT under G:\KEY; secrets.cmd only references the path
// (batch `for /f` reads the content at runtime, so no plaintext token sits in secrets.cmd).
// Rotate a token = edit the file CONTENT (path unchanged). Re-link = change the path here
// (for first-time setup or migration).
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const LINKS_PATH = path.join(DIR, 'links.json');
const PORT = Number(process.env.SECRETS_LINK_PORT ?? 7782);

function loadLinks() {
  return JSON.parse(fs.readFileSync(LINKS_PATH, 'utf8'));
}
function saveLinks(links) {
  fs.writeFileSync(LINKS_PATH, JSON.stringify(links, null, 2) + '\n', 'utf8');
}
function readTokenFile(file) {
  try { return fs.readFileSync(file, 'utf8').trim(); } catch { return null; }
}
function mask(token) {
  if (token == null) return { ok: false, text: '（文件缺失）' };
  if (token === '') return { ok: false, text: '（文件为空）' };
  const head = token.slice(0, 4);
  const tail = token.slice(-2);
  return { ok: true, text: `${head}…${tail}（len ${token.length}）` };
}

function generateSecretsCmd(links) {
  const lines = [
    '@echo off',
    'rem Generated by secrets-link panel. Tokens live in G:\\KEY file CONTENT.',
    'rem Rotate = edit the file content; re-link = change the path in the panel.',
    ''
  ];
  for (const [k, v] of Object.entries(links.extra ?? {})) lines.push(`set "${k}=${v}"`);
  lines.push('');
  for (const t of links.tokens) {
    lines.push(`for /f "usebackq delims=" %%i in ("${t.file}") do set "${t.var}=%%i"`);
  }
  lines.push('');
  return lines.join('\r\n');
}

function regenerate(links) {
  const cmd = generateSecretsCmd(links);
  let target = links.target;
  let wrote = false;
  let error = null;
  if (target) {
    try {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, cmd, 'utf8');
      wrote = true;
    } catch (e) {
      error = String(e?.message ?? e);
    }
  }
  return { target, wrote, error, cmd };
}

function snapshot() {
  const links = loadLinks();
  const tokens = links.tokens.map((t) => {
    const content = readTokenFile(t.file);
    const m = mask(content);
    return { var: t.var, file: t.file, exists: content != null, mask: m.text };
  });
  return { links, tokens };
}

