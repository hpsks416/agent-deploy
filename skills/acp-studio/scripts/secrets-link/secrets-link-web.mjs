const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://127.0.0.1:${PORT}`);
  const json = (obj, code = 200) => { res.writeHead(code, { 'Content-Type': 'application/json; charset=utf-8' }); res.end(JSON.stringify(obj)); };
  try {
    if (req.method === 'GET' && url.pathname === '/') { res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' }); res.end(HTML); return; }
    if (req.method === 'GET' && url.pathname === '/api/links') { json(snapshot()); return; }

    let body = '';
    for await (const chunk of req) body += chunk;
    const data = JSON.parse(body || '{}');
    const links = loadLinks();

    if (req.method === 'POST' && url.pathname === '/api/update') {
      const ws = activeWs(links);
      if (ws.tokens[data.index]) ws.tokens[data.index].file = data.file;
      saveLinks(links);
      json({ ...snapshot(), regen: regenerate(links) });
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/regen') {
      json({ ...snapshot(), regen: regenerate(links) });
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/select') {
      links.active = Number(data.index);
      saveLinks(links);
      json(snapshot());
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/add') {
      links.workspaces.push({ name: data.name || '新工作区', target: '', tokens: [], extra: {} });
      links.active = links.workspaces.length - 1;
      saveLinks(links);
      json(snapshot());
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/delete') {
      if (links.workspaces.length > 1) {
        links.workspaces.splice(Number(data.index), 1);
        links.active = 0;
        saveLinks(links);
      }
      json(snapshot());
      return;
    }
    if (req.method === 'POST' && url.pathname === '/api/encrypt') {
      const ws = activeWs(links);
      const identity = (ws.age && ws.age.identity) || '';
      const ageBin = (ws.age && ws.age.bin) || 'age';
      if (!identity || !ageBin) { json({ ...snapshot(), error: '未配置 age.identity / age.bin' }); return; }
      const helper = path.join(DIR, 'encrypt-token.py');
      let ok = 0, firstErr = null;
      for (const i of (data.indices || [])) {
        const t = ws.tokens[i];
        if (!t) continue;
        try {
          execFileSync(PY, [helper, t.file, ageBin, identity], { encoding: 'utf8' });
          t.file = t.file + '.zip';
          ok++;
        } catch (e) {
          if (!firstErr) firstErr = String(e?.stderr || e?.message || e);
        }
      }
      saveLinks(links);
      json({ ...snapshot(), encrypted: ok, error: firstErr });
      return;
    }
    res.writeHead(404); res.end('not found');
  } catch (e) {
    json({ error: String(e?.message ?? e) }, 500);
  }
});

server.on('error', (e) => {
  if (e.code === 'EADDRINUSE') {
    console.log(`secrets-link already running at http://127.0.0.1:${PORT} — opening it`);
    try { execSync(`start http://127.0.0.1:${PORT}`); } catch {}
    process.stdin.resume();
    return;
  }
  throw e;
});

server.listen(PORT, '127.0.0.1', () => {
  console.log(`secrets-link panel: http://127.0.0.1:${PORT}`);
  try { execSync(`start http://127.0.0.1:${PORT}`); } catch {}
});
